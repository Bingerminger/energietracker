#!/usr/bin/env node
/* =========================================================================
   build-setup-guide.mjs — der Wegweiser für die Doku (v3.12.0, Paket wegweiser).

   Eine Quelle: Die Wege stehen in public/js/lib/setup-scenes.js und in den
   Katalogen. Dieses Werkzeug zeichnet daraus dieselben Bilder als SVG-Dateien
   und schreibt die Seite docs/einstieg/wegweiser.md (Deutsch, Englisch). Von
   Hand gepflegt wird hier nichts, sonst liefen Bild, App und Doku auseinander.

     node tools/build-setup-guide.mjs           # schreibt die Dateien
     node tools/build-setup-guide.mjs --check   # vergleicht nur, Exit 1 bei Abweichung

   Die Bilder bringen ihre Farben mit, gelesen aus tokens.css und components.css,
   und folgen über prefers-color-scheme dem System: Als <img> erreicht sie das
   Thema der App nicht. Darum haben sie einen eigenen, deckenden Hintergrund.
   ========================================================================= */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SETUP_IDS, SETUPS, sceneSvg, sceneFlows, setupLabels, setupsFor, anchorFor } from '../public/js/lib/setup-scenes.js';
import { docPagePath } from '../public/js/lib/docs.js';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const CHECK = process.argv.includes('--check');
const LANGS = ['de', 'en'];
const IMG_DIR = 'docs/ui/wegweiser';
const PAGE = { de: 'docs/einstieg/wegweiser.md', en: 'docs/en/einstieg/wegweiser.md' };

// Was nur die Doku-Seite braucht (die App sagt es anders); alles andere kommt aus den Katalogen
const GLUE = {
  de: {
    title: 'Wegweiser: Welcher Weg passt zu dir?',
    langs: '**Deutsch** · [English](../en/einstieg/wegweiser.md)',
    index: '[← Kompendium-Index](../README.md)',
    made: 'Erzeugt von tools/build-setup-guide.mjs aus public/js/lib/setup-scenes.js und den Katalogen. Nicht von Hand ändern.',
    inApp: 'In der App steht derselbe Wegweiser unter **Hilfe → Wegweiser**, mit der Kurzauswahl zum Antippen. Der Einrichtungsassistent stellt dieselben drei Fragen. Die Schritte stehen in den verlinkten Anleitungen, hier steht nur der Weg.',
    head: '| Frage | Antwort | Weg |',
    anyTwo: 'Zwei oder mehr davon',
    none: 'Nichts davon',
    inTheApp: 'in der App:',
  },
  en: {
    title: 'Setup guide: which way suits you?',
    langs: '[Deutsch](../../einstieg/wegweiser.md) · **English**',
    index: '[← Compendium index](../README.md)',
    made: 'Generated by tools/build-setup-guide.mjs from public/js/lib/setup-scenes.js and the catalogs. Do not edit by hand.',
    inApp: 'The app has the same guide under **Help → Setup guide**, with the quick choice to tap. The setup assistant asks the same three questions. The steps are in the linked guides; this page only shows the way.',
    head: '| Question | Answer | Way |',
    anyTwo: 'Two or more of these',
    none: 'None of these',
    inTheApp: 'in the app:',
  },
};

const catalog = (lang) => JSON.parse(readFileSync(join(ROOT, `public/locales/${lang}.json`), 'utf8'));

/** Übersetzung wie t(), aber je Sprache aus der Datei. */
function translator(lang) {
  const cat = catalog(lang);
  return (key, params) => {
    let str = key.split('.').reduce((a, k) => a?.[k], cat);
    if (typeof str !== 'string') throw new Error(`${lang}: Schlüssel fehlt: ${key}`);
    for (const [k, v] of Object.entries(params || {})) str = str.replaceAll(`{${k}}`, String(v));
    return str;
  };
}

// ── Farben und Regeln für die eigenständigen Bilder ──────────────────

const TOKENS = ['--bg-1', '--bg-2', '--border-2', '--text-1', '--text-2', '--accent', '--info', '--warning', '--danger', '--success'];
const SHARED = ['--font-sans', '--ill-line', '--ill-ink', '--ill-accent', '--ill-fill', '--ill-surface', '--ill-ground', '--ill-stroke', '--ill-stroke-strong'];

function styles() {
  const tokens = readFileSync(join(ROOT, 'public/css/tokens.css'), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
  const block = (head) => {
    const at = tokens.indexOf(head);
    if (at < 0) throw new Error(`tokens.css: ${head} fehlt`);
    return tokens.slice(at, tokens.indexOf('\n}', at));
  };
  const dark = block(':root {'), light = block('[data-theme="light"] {');
  const value = (src, name) => (src.match(new RegExp(`(?:^|\\s)${name}:\\s*([^;]+);`)) || [])[1]?.trim();
  const decls = (src, names, fallback = null) => names.map(n => {
    const v = value(src, n) ?? (fallback && value(fallback, n));
    if (!v) throw new Error(`tokens.css: ${n} fehlt`);
    return `${n}:${v.replace(/\s+/g, ' ')}`;
  }).join(';');
  const css = readFileSync(join(ROOT, 'public/css/components.css'), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
  const rules = css.split('\n').filter(l => /^\.ill (\*|\.ill-)[^{]*\{[^}]*\}\s*$|^\.ill-c-[a-z]+\s*\{[^}]*\}\s*$/.test(l)).map(l => l.replace(/\s+/g, ' ').trim());
  return `:root{${decls(light, TOKENS, dark)};${decls(dark, SHARED)}}`
    + `@media (prefers-color-scheme:dark){:root{${decls(dark, TOKENS)}}}`
    + rules.join('') + '.ill .ill-bg{fill:var(--bg-1);stroke:none}';
}

/** Eigenständige Datei: Maße, Farben und Hintergrund kommen zum Bild aus der App dazu. */
function standalone(svg, css) {
  const box = svg.match(/viewBox="0 0 (\d+) (\d+)"/);
  if (!box) throw new Error('Bild ohne viewBox');
  return `${svg
    .replace('<svg ', `<svg width="${box[1]}" height="${box[2]}" `)
    .replace('</title>', `</title><style>${css}</style><rect class="ill-bg" width="100%" height="100%"/>`)
    .replace(/\s*\n\s*/g, '')}\n`;
}

// ── Die Seite ────────────────────────────────────────────────────────

const imgName = (id, lang, variant) => `${id}.${lang}${variant === 'narrow' ? '.narrow' : ''}.svg`;

/** Die Marken aus den Katalogen (rich(): **fett**, `code`) sind schon Markdown. */
const md = (s) => s;

function page(lang) {
  const tr = translator(lang);
  const g = GLUE[lang];
  const labels = setupLabels(tr);
  const fromDir = dirname(PAGE[lang]);
  const toFile = (p) => relative(fromDir, p);
  const link = (l) => {
    const label = tr(l.label);
    if (l.url) return `[${label}](${l.url})`;
    if (l.scene) return `[${label}](#weg-${l.scene})`;
    if (l.app) return `(${g.inTheApp} **${label}**)`;
    const a = anchorFor(l.anchor, lang);
    return `[${label}](${toFile(docPagePath(l.doc, lang))}${a ? `#${a}` : ''})`;
  };
  const wayName = (id) => tr(`setups.scene.${SETUPS[id].key}.title`);
  const way = (id) => `[${wayName(id)}](#weg-${id})`;
  const nums = (n) => Array.from({ length: n }, (_, i) => i + 1);
  const answer = (q, o) => tr(`setups.quick.${q}.${o}`);
  const ask = (q) => tr(`setups.quick.${q}.question`);

  const out = [`# ${g.title}`, '', `<!-- ${g.made} -->`, '', g.langs, '', g.index, '', tr('setups.intro'), '', g.inApp, '',
    `## ${tr('setups.quick.title')}`, '', g.head, '|---|---|---|'];
  for (const [q, o, a] of [['smart', 'yes', { smart: 'yes' }], ['post', 'yes', { post: 'yes' }], ['ai', 'home', { ai: 'home' }], ['ai', 'out', { ai: 'out' }]]) {
    out.push(`| ${ask(q)} | ${answer(q, o)} | ${setupsFor(a).map(way).join(', ')} |`);
  }
  out.push(`| ${g.anyTwo} | | ${way('together')} |`);
  out.push(`| ${g.none} | | ${setupsFor({ smart: 'no' }).map(way).join(', ')} |`, '', tr('setups.quick.nothing'), '');

  for (const id of SETUP_IDS) {
    const s = SETUPS[id];
    const k = `setups.scene.${s.key}`;
    const text = (key) => md(tr(`${k}.${key}`, labels));
    const wide = toFile(`${IMG_DIR}/${imgName(id, lang, 'wide')}`), narrow = toFile(`${IMG_DIR}/${imgName(id, lang, 'narrow')}`);
    const alt = tr('setups.figure', { name: wayName(id) });
    const { inside, across } = sceneFlows(id, tr);
    const flow = (f) => `- ${f.from} → ${f.to}: ${f.label}`;
    out.push(`<a id="weg-${id}"></a>`, '', `## ${wayName(id)}`, '', tr(`${k}.teaser`), '',
      `<picture><source media="(max-width: 600px)" srcset="${narrow}"><img src="${wide}" alt="${alt}" width="760"></picture>`, '',
      `**${tr('setups.block.inside')}**`, '', ...inside.map(flow), '', `**${tr('setups.block.across')}**`, '', ...across.map(flow), '',
      `**${tr('setups.block.forWhom')}:** ${text('forWhom')}`, '', `**${tr('setups.block.get')}**`, '', ...nums(s.get).map(i => `- ${text(`get${i}`)}`), '');
    if (s.getLinks) out.push(s.getLinks.map(link).join(' · '), '');
    out.push(`**${tr('setups.block.need')}**`, '', `- ${tr('setups.block.software')}: ${text('software')}`, `- ${tr('setups.block.hardware')}: ${text('hardware')}`, '',
      `**${tr('setups.block.effort')}:** ${text('effort')}`, '', `**${tr('setups.block.steps')}**`, '',
      ...s.steps.map((links, i) => `${i + 1}. ${text(`step${i + 1}`)} ${links.map(link).join(' · ')}`), '',
      `**${tr('setups.block.data')}:** ${text('data')}`, '', `**${tr('setups.block.limits')}**`, '', ...nums(s.limits).map(i => `- ${text(`limit${i}`)}`), '',
      `**${tr('setups.block.detail')}:** ${text('detailIntro')}`, '', `**${tr('setups.block.addresses')}**`, '',
      ...s.detail.rows.map(r => `- ${tr(`${k}.row.${r.id}.label`)}: \`${r.addr}\`. ${text(`row.${r.id}.note`)}`), '');
    if (s.detail.code) out.push(`**${text('codeTitle')}**`, '', '```text', s.detail.code, '```', '');
    out.push(`**${tr('setups.block.notes')}**`, '', ...nums(s.detail.notes).map(i => `- ${text(`note${i}`)}`), '');
    if (s.detail.errors) out.push(`**${tr('setups.block.errors')}**`, '', ...nums(s.detail.errors).map(i => `- ${text(`err${i}.symptom`)}: ${text(`err${i}.fix`)}`), '');
    out.push(s.detail.sources.map(link).join(' · '), '', '---', '');
  }
  out.push(g.index, '');
  return out.join('\n');
}

// ── Schreiben oder vergleichen ───────────────────────────────────────

const files = new Map();
const css = styles();
for (const lang of LANGS) {
  const tr = translator(lang);
  for (const id of SETUP_IDS) for (const variant of ['wide', 'narrow']) {
    files.set(`${IMG_DIR}/${imgName(id, lang, variant)}`, standalone(sceneSvg(id, { variant, tr }), css));
  }
  files.set(PAGE[lang], page(lang));
}

let changed = 0;
for (const [rel, text] of files) {
  const abs = join(ROOT, rel);
  const old = existsSync(abs) ? readFileSync(abs, 'utf8') : null;
  if (old === text) continue;
  changed++;
  if (CHECK) { console.log(`veraltet: ${rel}`); continue; }
  mkdirSync(dirname(abs), { recursive: true });
  writeFileSync(abs, text);
  console.log(`geschrieben: ${rel}`);
}
if (existsSync(join(ROOT, IMG_DIR))) {
  for (const f of readdirSync(join(ROOT, IMG_DIR))) {
    const rel = `${IMG_DIR}/${f}`;
    if (files.has(rel)) continue;
    changed++;
    if (CHECK) console.log(`überzählig: ${rel}`);
    else { rmSync(join(ROOT, rel)); console.log(`entfernt: ${rel}`); }
  }
}
console.log(`${files.size} Dateien, ${changed} ${CHECK ? 'abweichend' : 'geändert'}`);
if (CHECK && changed) process.exit(1);
